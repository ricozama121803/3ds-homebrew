#!/usr/bin/env python3
"""Exports hero.blend to the game: ../../source/hero_mesh.h (indexed triangle meshes, joint-local, game axes) and ../gfx/hero.png (the suit texture).
Every object named hero_<part> is exported (modifiers applied, triangulated, smooth corner normals). Edit hero.blend in Blender, save, run this, rebuild.
Run: ../../../tools/blender-venv/bin/python export_hero.py"""
import os, shutil, bpy
from mathutils import Vector

HERE = os.path.dirname(os.path.abspath(__file__))
ORDER = ["torso", "head", "upperarm", "forearm", "hand", "thigh", "shin", "foot"]

def to_game(v):                      # Blender (Z up, hero faces -Y)  ->  game (Y up, hero faces +Z)
    return (v[0], v[2], -v[1])

def export_part(obj, dg):
    ev = obj.evaluated_get(dg); me = ev.to_mesh()
    me.calc_loop_triangles()
    rot = obj.matrix_basis.to_3x3()                                       # rotation/scale of the object; its translation is the joint and is dropped
    uvl = me.uv_layers.active
    verts, index, out = {}, [], []
    cn = me.corner_normals
    for tri in me.loop_triangles:
        for li in tri.loops:
            vi = me.loops[li].vertex_index
            p = to_game(rot @ me.vertices[vi].co)
            n = to_game((rot.to_quaternion() @ cn[li].vector).normalized())
            u, v = uvl.data[li].uv
            key = (round(p[0], 4), round(p[1], 4), round(p[2], 4), round(n[0], 3), round(n[1], 3), round(n[2], 3), round(u, 4), round(v, 4))
            if key not in verts: verts[key] = len(out); out.append(key)
            index.append(verts[key])
    ev.to_mesh_clear()
    return out, index

def main():
    bpy.ops.wm.open_mainfile(filepath=os.path.join(HERE, "hero.blend"))
    dg = bpy.context.evaluated_depsgraph_get()
    lines = ["// Generated by assets/hero/export_hero.py from hero.blend - do not edit by hand.",
             "// Joint-local meshes in game axes (x = hero's left, y up, z front). Vertex: x y z nx ny nz u v.", "#pragma once",
             "typedef struct { int nv, ni; const float *v; const unsigned short *i; } HeroPart;",
             "enum { " + ", ".join("HP_" + n.upper() for n in ORDER) + ", HP_COUNT };", ""]
    total_tris = 0
    for n in ORDER:
        obj = bpy.data.objects["hero_" + n]
        verts, idx = export_part(obj, dg)
        total_tris += len(idx) // 3
        lines.append(f"static const float hero_v_{n}[] = {{")
        for k in verts: lines.append("\t" + ", ".join(f"{x:.4f}f" for x in k) + ",")
        lines.append("};")
        lines.append(f"static const unsigned short hero_i_{n}[] = {{" + ", ".join(map(str, idx)) + "};")
        lines.append("")
    lines.append("static const HeroPart HERO_PARTS[HP_COUNT] = {")
    for n in ORDER:
        lines.append(f"\t{{ sizeof hero_v_{n} / sizeof(float) / 8, sizeof hero_i_{n} / sizeof(unsigned short), hero_v_{n}, hero_i_{n} }},")
    lines.append("};")
    open(os.path.join(HERE, "..", "..", "source", "hero_mesh.h"), "w").write("\n".join(lines) + "\n")
    shutil.copy(os.path.join(HERE, "hero_atlas.png"), os.path.join(HERE, "..", "gfx", "hero.png"))
    print("exported", len(ORDER), "parts,", total_tris, "triangles per side-set (mirrored limbs double the arm/leg parts)")

main()
