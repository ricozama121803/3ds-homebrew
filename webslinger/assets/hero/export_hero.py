#!/usr/bin/env python3
"""Export welded skin, four weights, common-axis inverse binds, hierarchy and UV corners."""
import bpy,os,sys,shutil,re,json
sys.path.insert(0,os.path.dirname(__file__))
from rig import BONES,game
HERE=os.path.dirname(os.path.abspath(__file__))
bpy.ops.wm.open_mainfile(filepath=os.path.join(HERE,'hero.blend'))
o=bpy.data.objects['hero_body'];me=o.data;me.calc_loop_triangles()
def floats(a):return '{'+','.join(f'{v:.6f}f' for v in a)+'}'
lines=['// Generated by assets/hero/export_hero.py. Common-axis bind frames; inverse bind = T(-head).','#pragma once',f'#define HERO_NV {len(me.vertices)}',f'#define HERO_NI {len(me.loop_triangles)*3}',f'#define HERO_NB {len(BONES)}','enum { '+','.join('HB_'+b[0].upper() for b in BONES)+' };','typedef struct { float p[3],n[3],ao,w[4]; unsigned char b[4]; } HeroVertex;','typedef struct { signed char parent; float head[3],tail[3]; } HeroBone;','typedef struct { unsigned short v; float uv[2]; } HeroCorner;','static const HeroBone hero_bones[HERO_NB] = {']
for name,parent,h,t in BONES:lines.append('{'+str(parent)+','+floats(h)+','+floats(t)+'},')
lines+=['};','static const HeroVertex hero_vertices[HERO_NV] = {']
lookup={b[0]:i for i,b in enumerate(BONES)}
for v in me.vertices:
 weights=sorted([(g.weight,lookup[o.vertex_groups[g.group].name]) for g in v.groups if g.weight>1e-7],reverse=True)[:4];total=sum(w for w,b in weights);assert total>.99
 weights+=[(0,0)]*(4-len(weights));w=[w/total for w,b in weights];b=[b for w,b in weights]
 lines.append('{'+floats(game(v.co))+','+floats(game(v.normal))+f',{me.attributes["suit_ao"].data[v.index].value:.6f}f,'+floats(w)+',{'+','.join(map(str,b))+'}},')
lines+=['};','static const HeroCorner hero_corners[HERO_NI] = {']
for tri in me.loop_triangles:
 for li in tri.loops:lines.append('{'+str(me.loops[li].vertex_index)+','+floats(me.uv_layers.active.data[li].uv)+'},')
lines+=['};']
cap=int(re.search(r'#define CAP_D_HERO\s+(\d+)',open(os.path.join(HERE,'../../source/scene.h')).read()).group(1));assert len(me.loop_triangles)*3<=cap
open(os.path.join(HERE,'../../source/hero_mesh.h'),'w').write('\n'.join(lines)+'\n')
shutil.copy(os.path.join(HERE,'hero_atlas.png'),os.path.join(HERE,'../gfx/hero.png'))
print(f'Export: {len(me.vertices)} skinned vertices, {len(me.loop_triangles)} triangles, {len(BONES)} bones, {len(me.loop_triangles)*3}/{cap} draw vertices')
