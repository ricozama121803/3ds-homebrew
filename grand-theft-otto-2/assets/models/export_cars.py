#!/usr/bin/env python3
"""cars.blend -> source/car_mesh.h: per kind a body mesh (flat-shaded triangles with a colour, a tag and a normal) plus one shared wheel mesh.
Local car frame in the header: +X = the car's left, +Y up, +Z forward (Blender (X, Y, Z) -> (X, Z, -Y)). Faces that point straight down are dropped.
Tags: 0 fixed colour, 1 body paint (tinted per car), 2 tail light (brighter when braking), 3 always bright (head lights, signs), 4 / 5 red / blue light bar.
Usage: blender-venv/python export_cars.py"""
import bpy, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from build_cars import SPECS, LINEUP, wheel_spots
HERE = os.path.dirname(os.path.abspath(__file__))
bpy.ops.wm.open_mainfile(filepath=os.path.join(HERE, "cars.blend"))
KINDS = [k for k, _ in LINEUP]                           # order must match the CAR_* enum in game.h
TAGS = {"taillight": 2, "headlight": 3, "amber": 3, "sign": 3, "lightR": 4, "lightB": 5}


def srgb(c):
    return [max(0.0, min(1.0, v)) ** (1 / 2.2) for v in c[:3]]


def f(a):
    return "{" + ",".join(f"{v:.4f}f" for v in a) + "}"


def g(v):
    return (v[0], v[2], -v[1])


pal, pal_index = [], {}


def colour(m):
    key = tuple(round(x, 4) for x in srgb(m.diffuse_color))
    if key not in pal_index:
        pal_index[key] = len(pal)
        pal.append(key)
    return pal_index[key]


def tag_of(m):
    base = m.name.split(".")[0]
    if base == "paint":
        return 1
    return TAGS.get(base, 0)


def mesh_block(name, ob, cull_down):
    me = ob.data
    me.calc_loop_triangles()
    verts, tris = [], []
    for t in me.loop_triangles:
        n = t.normal
        if cull_down and n.z < -0.8:
            continue
        m = me.materials[t.material_index]
        idx = []
        for vi in t.vertices:
            p = tuple(round(c, 4) for c in me.vertices[vi].co)
            if p not in verts:
                verts.append(p)
            idx.append(verts.index(p))
        tris.append((idx, colour(m), tag_of(m), g(n)))
    out = [f"static const float {name}_v[][3] = {{" + ",".join(f(g(p)) for p in verts) + "};",
           f"static const CarTri {name}_t[] = {{" + ",".join("{{" + ",".join(map(str, i)) + "}," + f"{c},{tg}," + f(n) + "}" for i, c, tg, n in tris) + "};"]
    return out, len(verts), len(tris)


lines = ["// Generated by assets/models/export_cars.py from cars.blend. Local frame: +X = the car's left, +Y up, +Z forward.", "#pragma once",
         "typedef struct { unsigned short v[3]; unsigned char col, tag; float n[3]; } CarTri;",
         "typedef struct { int nv, nt; const float (*v)[3]; const CarTri *t; float hl, hw, wheelR, track, front, rear; } CarModel;"]
blocks, models = [], []
for k in KINDS:
    ob = bpy.data.objects[k]
    out, nv, nt = mesh_block("car_" + k, ob, True)
    blocks += out
    sp = SPECS[k]
    st = sp["st"]
    models.append("{" + f"{nv},{nt},car_{k}_v,car_{k}_t,{sp['L'] / 2:.3f}f,{max(s[2][0] for s in st):.3f}f,{sp['wheelR']:.3f}f,{sp['track']:.3f}f,{-sp['front']:.3f}f,{-sp['rear']:.3f}f" + "}")
    print(k, nv, "vertices", nt, "triangles")
wout, wnv, wnt = mesh_block("wheel", bpy.data.objects["wheel"], False)
print("wheel", wnv, "vertices", wnt, "triangles")
lines += blocks + wout
lines += [f"#define CAR_NPAL {len(pal)}", "static const float car_palette[CAR_NPAL][3] = {" + ",".join(f(c) for c in pal) + "};",
          f"#define WHEEL_NV {wnv}", f"#define WHEEL_NT {wnt}",
          "static const CarModel car_models[] = {" + ",".join(models) + "};"]
open(os.path.join(HERE, "../../source/car_mesh.h"), "w").write("\n".join(lines) + "\n")
