"""Palm trees (two variants) for the LA streets and the beach, exported as street props: source/palm_mesh.h
(vertex = x y z nx ny nz r g b with a flat normal per triangle, game axes y up, origin at the foot).
Usage: blender-venv/python build_palm.py  [render_prefix]   (also writes palms.blend; with a prefix it renders a preview)"""
import sys, os, random
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
