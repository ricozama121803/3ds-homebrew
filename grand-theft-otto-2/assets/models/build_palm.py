def palm(name, height, trunk_r, fronds, reach, droop, seed):
    rnd = random.Random(seed)
    TRUNK = material("palm_trunk", "#8A6A48", 0.9)
    RING = material("palm_ring", "#6E5238", 0.9)
    LEAF = material("palm_leaf", "#3F8A34", 0.8)
    LEAF2 = material("palm_leaf2", "#5BA23C", 0.8)
    b = Builder(name)
    bend = rnd.uniform(0.5, 1.1) * (height / 9.0)
    ang0 = rnd.uniform(0, 6.28)
    bx, by = math.cos(ang0), math.sin(ang0)
    rows = 4
    rings, mats = [], []
    for i in range(rows):
        t = i / (rows - 1)
        off = bend * t * t
        c = V(bx * off, by * off, t * height)
        r = trunk_r * (1.0 - 0.38 * t) * (1.25 if i == 0 else 1.0)
        rings.append(b.ring(c, V(1, 0, 0), V(0, 1, 0), r, r, 6, 2.0))
        mats.append(TRUNK if i % 2 == 0 else RING)
    b.loft(rings, mats[:-1], caps=(False, True))
    top = V(bx * bend, by * bend, height)
    for k in range(fronds):
        a = k * math.tau / fronds + rnd.uniform(-0.2, 0.2)
        dx, dy = math.cos(a), math.sin(a)
        L = reach * rnd.uniform(0.9, 1.15)
        upright = (k % 3 == 2)
        hs, rise, fall = (0.42, 0.85 * L, 0.35 * L) if upright else (1.0, 0.38 * L, droop * 0.75 * L)
        pts = []
        segs = 2
        for s in range(segs + 1):
            t = s / segs
            w = 0.62 * math.sin(math.pi * (0.08 + 0.84 * t)) + 0.04
            p = top + V(dx * L * hs * t, dy * L * hs * t, rise * math.sin(math.pi * 0.5 * t) - fall * t * t + 0.15)
            sx, sy = -dy * w, dx * w
            pts.append((p + V(sx, sy, 0), p - V(sx, sy, 0)))
        for s in range(segs):
            f = b.bm.faces.new((b.vert(pts[s][0]), b.vert(pts[s][1]), b.vert(pts[s + 1][1]), b.vert(pts[s + 1][0])))
            f.material_index = b.mi(LEAF if (k + s) % 2 == 0 else LEAF2)
    return b.build()


def export(objs, path):
    def srgb(c):
        return [max(0.0, min(1.0, v)) ** (1 / 2.2) for v in c[:3]]
    lines = ["// Generated by assets/models/build_palm.py - do not edit by hand.", "// Palm props, same layout as props_mesh.h: vertex = x y z nx ny nz r g b, origin at the foot, y up.", "#pragma once", "#include \"props_mesh.h\""]
    names = []
    for ob in objs:
        me = ob.data
        me.calc_loop_triangles()
        v, idx = [], []
        for t in me.loop_triangles:
            n = t.normal
            if n.z < 0 and me.materials[t.material_index].name.startswith("palm_leaf"):
                n = -n                                                          # leaves are two-sided; light them from above
            col = srgb(me.materials[t.material_index].diffuse_color)
            for vi in t.vertices:
                p = me.vertices[vi].co
                idx.append(len(v) // 9)
                v += [p.x, p.z, -p.y, n.x, n.z, -n.y, *col]
        lines.append(f"static const float prop_v_{ob.name}[] = {{" + ",".join(f"{x:.3f}f" for x in v) + "};")
        lines.append(f"static const unsigned short prop_i_{ob.name}[] = {{" + ",".join(map(str, idx)) + "};")
        names.append(ob.name)
    lines.append(f"#define PALM_COUNT {len(names)}")
    lines.append("static const PropMesh PALMS[PALM_COUNT] = {" + ",".join(f"{{ sizeof prop_v_{n} / sizeof(float) / 9, sizeof prop_i_{n} / sizeof(unsigned short), prop_v_{n}, prop_i_{n} }}" for n in names) + "};")
    open(path, "w").write("\n".join(lines) + "\n")


