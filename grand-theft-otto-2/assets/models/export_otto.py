#!/usr/bin/env python3
"""otto.blend -> source/otto_mesh.h and ped.blend -> source/ped_mesh.h: skinned vertices (rig space, up to 4 bone weights) and triangles, each with a colour ROLE
(shirt, trousers, skin, ...). Otto has a fixed outfit; pedestrians fill the roles in per person. Usage: blender-venv/python export_otto.py"""
import bpy, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from rig_otto import BONES, NAMES, INDEX, game
HERE = os.path.dirname(os.path.abspath(__file__))

ROLES = ["suit", "suit_dark", "pants", "pants_dark", "skin", "skin_dark", "black", "beanie", "cuff", "boot", "sack", "tie", "white", "dollar"]


def lin2srgb(c):
    return [max(0.0, min(1.0, v)) ** (1 / 2.2) for v in c[:3]]


def f(a):
    return "{" + ",".join(f"{v:.5f}f" for v in a) + "}"


def export(blend, objname, prefix, outfile, first):
    bpy.ops.wm.open_mainfile(filepath=os.path.join(HERE, blend))
    ob = bpy.data.objects[objname]
    me = ob.data
    me.calc_loop_triangles()
    groups = {g.index: g.name for g in ob.vertex_groups}
    colors = {}
    for m in me.materials:
        colors.setdefault(m.name.split(".")[0], lin2srgb(m.diffuse_color))
    lines = ["// Generated by assets/models/export_otto.py from " + blend + ". Rig space: origin at the pelvis joint, +X = Otto's left, +Y up, +Z forward.", "#pragma once"]
    if first:
        lines += [f"#define OTTO_NB {len(BONES)}", "enum { " + ",".join("RL_" + r.upper() for r in ROLES) + ", RL_COUNT };",
                  "enum { " + ",".join("OB_" + n.upper() for n in NAMES) + " };",
                  "typedef struct { float p[3], w[4]; unsigned char b[4]; } OttoVert;",
                  "typedef struct { unsigned short v[3]; unsigned char role; } OttoTri;",
                  "typedef struct { signed char parent; float head[3], tail[3]; } OttoBone;",
                  "static const OttoBone otto_bones[OTTO_NB] = {"]
        for name, parent, h, t in BONES:
            lines.append("{" + str(parent) + "," + f(h) + "," + f(t) + "},")
        lines += ["};", "static const float otto_colors[RL_COUNT][3] = {"] + [f(colors.get(r, [0.5, 0.5, 0.5])) + "," for r in ROLES] + ["};"]
    lines += [f"#define {prefix.upper()}_NV {len(me.vertices)}", f"#define {prefix.upper()}_NT {len(me.loop_triangles)}", f"static const OttoVert {prefix}_verts[{prefix.upper()}_NV] = {{"]
    for v in me.vertices:
        ws = sorted([(g.weight, INDEX[groups[g.group]]) for g in v.groups if g.weight > 1e-4], reverse=True)[:4]
        tot = sum(w for w, _ in ws)
        assert tot > 0.5, f"vertex {v.index} has no weights"
        ws += [(0.0, 0)] * (4 - len(ws))
        lines.append("{" + f(game(v.co)) + "," + f([w / tot for w, _ in ws]) + ",{" + ",".join(str(b) for _, b in ws) + "}},")
    lines += ["};", f"static const OttoTri {prefix}_tris[{prefix.upper()}_NT] = {{"]
    for t in me.loop_triangles:
        role = ROLES.index(me.materials[t.material_index].name.split(".")[0])
        lines.append("{{" + ",".join(str(i) for i in t.vertices) + "}," + str(role) + "},")
    lines.append("};")
    open(os.path.join(HERE, outfile), "w").write("\n".join(lines) + "\n")
    print(f"{prefix}: {len(me.vertices)} vertices, {len(me.loop_triangles)} triangles")


export("otto.blend", "otto", "otto", "../../source/otto_mesh.h", True)
export("ped.blend", "ped", "ped", "../../source/ped_mesh.h", False)
